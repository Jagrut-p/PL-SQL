/*
WRITE A PROGRAM WHICH WILL ASK FOR Principle amount, 
IntRest rate AND Number of years VALUES. CALCULATE 
AND DISPLAY SIMPLE INTERST AMOUNT , TOTAL REPAYMENT 
AMOUNT AND EMI (EQUATED MONTHLY INSTALLMENT)
 

SI = P x R x N / 100


CHECK : 200000    10%    2 YRS    SIMPLE INTEREST : 40000    TOTAL REPAYMENT : 240000     EMI : 10000
 
CHECK : 100000    4%     5 YRS    SIMPLE INTEREST : 20000    TOTAL REPAYMENT : 120000     EMI : 2000
*/
DECLARE
P NUMBER := &PRINCIPLE_AMOUNT;
R NUMBER := &RATE;
N NUMBER := &YEAR;
EMI NUMBER := (P*R*N)/100;
SI NUMBER := EMI * N;
TR NUMBER := EMI + SI;
BEGIN
DBMS_OUTPUT.PUT_LINE('SIMPLE INTEREST: ' || SI);
DBMS_OUTPUT.PUT_LINE('EMI: ' || EMI);
DBMS_OUTPUT.PUT_LINE('TOTAL REPAYMENT: ' || TR);
END;
/