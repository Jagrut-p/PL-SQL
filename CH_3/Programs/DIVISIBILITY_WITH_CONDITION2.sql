/*
ASK FOR TWO NUMBERS. ((USE ONLY 'NUMBER' DATA TYPE WITH PRECESION AND SCALE BOTH). LIKE THIS NUMBER(5,2). 
DIVIDE FIRST NUMBER WITH SECOND, IF IT IS DIVISIBLE (REMAINDER LESS) THEN DISPLAY 'DIVISIBLE'.

(WITHOUT USING ANY NUMBER FUNCTIONS)
*/
DECLARE
NO1 NUMBER(5,2):= &NO1;
NO2 NUMBER(5,2):= &NO2;
ANS1 NUMBER(5,2);
ANS2 NUMBER(5,2);
ANS3 NUMBER(5,2);
BEGIN
ANS1 := TO_CHAR(NO1/NO2,999);
ANS2 := ANS1 * NO2;
ANS3 := NO1 - ANS2;
IF ANS3 = 0 THEN 
DBMS_OUTPUT.PUT_LINE('DIVISIBLE');
END IF;
END;
/