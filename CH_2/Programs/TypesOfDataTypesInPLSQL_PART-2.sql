/*
ASK FOR EMPLOYEE_ID AND DISPLAY FULL_NAME AND HIRE_DATE. ALSO FIND TOTAL 
DAYS WORKED (INTEGER) , TOTAL MONTHS WORKED (INTEGER) AND DISPLAY IT.
*/
DECLARE 
EID EMPLOYEES.EMPLOYEE_ID%TYPE := &EMPID;
FN EMPLOYEES.FIRST_NAME%TYPE;
LN EMPLOYEES.LAST_NAME%TYPE;
HD EMPLOYEES.HIRE_DATE%TYPE;
BEGIN
SELECT FIRST_NAME, LAST_NAME, HIRE_DATE INTO FN, LN, HD FROM EMPLOYEES WHERE EMPLOYEE_ID = EID;
DBMS_OUTPUT.PUT_LINE('EMPLOYEE_ID: ' || EID);
DBMS_OUTPUT.PUT_LINE('FULL NAME: ' || FN || LN);
DBMS_OUTPUT.PUT_LINE('HIRE_DATE: ' || HD);
DBMS_OUTPUT.PUT_LINE('DAYS WORKED: ' || TRUNC(CURRENT_DATE - HD));
DBMS_OUTPUT.PUT_LINE('DAYS WORKED: ' || TRUNC(MONTHS_BETWEEN(CURRENT_DATE, HD)));
END;
/
