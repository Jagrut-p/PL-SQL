/*
ASK FOR EMPLOYEE_ID AND DISPLAY EMPLOYEE'S FIRST_NAME AND HIRE_DATE 
WITH HIS/HER MANAGER NAME AND HIREDATE. 

DISPLAY WEEKS DIFFERENCE AND QUARTERS DIFFERENCE. 
(DIFFERENCE MUST BE INTEGER ONLY)
*/
DECLARE 
EID EMPLOYEES.EMPLOYEE_ID%TYPE := &EMPLOYEE_ID;
FN EMPLOYEES.FIRST_NAME%TYPE;
HD EMPLOYEES.HIRE_DATE%TYPE;
MFN EMPLOYEES.FIRST_NAME%TYPE;
MHD EMPLOYEES.HIRE_DATE%TYPE;
WED INT;
QD INT;
BEGIN
SELECT E.FIRST_NAME, E.HIRE_DATE, M.FIRST_NAME, M.HIRE_DATE, 
TRUNC((MONTHS_BETWEEN(M.HIRE_DATE, E.HIRE_DATE)/3)), TRUNC((M.HIRE_DATE - E.HIRE_DATE)/7)
INTO FN, HD, MFN, MHD, WED, QD FROM EMPLOYEES E LEFT JOIN EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID 
WHERE E.EMPLOYEE_ID = EID;
DBMS_OUTPUT.PUT_LINE('EMPLOYEE NAME:       ' || EID);
DBMS_OUTPUT.PUT_LINE('EMPLOYEE FIRST NAME: ' || FN);
DBMS_OUTPUT.PUT_LINE('EMPLOYEE HIRE_DATE:  ' || HD);
DBMS_OUTPUT.PUT_LINE('MANAGER FIRST NAME:  ' || MFN);
DBMS_OUTPUT.PUT_LINE('MANAGER HIRE_DATE:   ' || MHD);
DBMS_OUTPUT.PUT_LINE('WEEK DIFFERENCE:     ' || WED);
DBMS_OUTPUT.PUT_LINE('QUARTER:             ' || QD);
END;
