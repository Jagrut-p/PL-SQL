/*
ASK FOR DEPARTMENT_ID AND DISPLAY IT'S CITY AND COUNTRY_NAME
EDLCR
*/
DECLARE
DID EMPLOYEES.DEPARTMENT_ID%TYPE := &DID;
CY LOCATIONS.CITY%TYPE;
CN COUNTRIES.COUNTRY_NAME%TYPE;
BEGIN
SELECT DEPARTMENT_ID, CITY, COUNTRY_NAME INTO DID, CY, CN FROM DEPARTMENTS 
JOIN LOCATIONS USING(LOCATION_ID) INNER JOIN COUNTRIES USING (COUNTRY_ID) 
WHERE DEPARTMENT_ID = DID;
DBMS_OUTPUT.PUT_LINE('DEPARTMENT_ID: ' || DID);
DBMS_OUTPUT.PUT_LINE('CITY: ' || CY);
DBMS_OUTPUT.PUT_LINE('COUNTRY: ' || CN);
END;
