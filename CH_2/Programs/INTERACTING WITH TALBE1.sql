/*
ASK FOR EMPLOYEE_ID AND DISPLAY LAST_NAME , PHONE_NUMBER , JOB_ID.
*/
DECLARE
EID EMPLOYEES.EMPLOYEE_ID%TYPE:= &EMPID;
LT EMPLOYEES.LAST_NAME%TYPE;
PN EMPLOYEES.PHONE_NUMBER%TYPE;
JOID EMPLOYEES.JOB_ID%TYPE;
BEGIN
SELECT LAST_NAME, PHONE_NUMBER, JOB_ID INTO LT, PN, JOID FROM EMPLOYEES WHERE EMPLOYEE_ID = EID;
DBMS_OUTPUT.PUT_LINE('EMPLOYEE_ID: ' || EID);
DBMS_OUTPUT.PUT_LINE('LAST_NAME: ' || LT);
DBMS_OUTPUT.PUT_LINE('PHONE_NUMBER: ' || PN);
DBMS_OUTPUT.PUT_LINE('JOB_ID: ' || JOID);
END;
