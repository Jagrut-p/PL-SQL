/*
ASK FOR EMPLOYEE_ID AND DISPLAY EMPLOYEE'S FIRST_NAME AND SALARY WITH 
HIS/HER MANAGER NAME AND SALARY.
*/
DECLARE
EID EMPLOYEES.EMPLOYEE_ID%TYPE := &EMPLOYEE_ID;
FN EMPLOYEES.FIRST_NAME%TYPE;
SY EMPLOYEES.SALARY%TYPE;
MN EMPLOYEES.FIRST_NAME%TYPE;
MSY EMPLOYEES.SALARY%TYPE;
BEGIN
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.SALARY, M.FIRST_NAME, M.SALARY 
INTO EID, FN, SY, MN, MSY FROM EMPLOYEES E LEFT JOIN EMPLOYEES M ON 
E.MANAGER_ID = M.EMPLOYEE_ID  
WHERE E.EMPLOYEE_ID = EID;
DBMS_OUTPUT.PUT_LINE('EMPLOYEE_ID:    ' || EID);
DBMS_OUTPUT.PUT_LINE('FIRST_NAME:     ' || FN);
DBMS_OUTPUT.PUT_LINE('SALARY:         ' || SY);
DBMS_OUTPUT.PUT_LINE('MANAGER NAME:   ' || MN);
DBMS_OUTPUT.PUT_LINE('MANAGER SALARY: ' || MSY);
END;
