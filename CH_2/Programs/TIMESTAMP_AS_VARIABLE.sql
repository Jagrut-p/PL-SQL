/*
DECLARE VARIABLES TO STORE : TIMESTAMP , DAY TO SECOND AND YEAR TO MONTH 
INTERVAL TYPE VALUES

ASK USER FOR ALL VALUES.

DISPLAY TIMESTAMP , TIMESTAMP + DAY TO SECOND , TIMESTAMP - YEAR TO MONTH 
AND 

TIMESTAMP - DAY TO SECOND + YEAR TO MONTH
*/
DECLARE 
TS TIMESTAMP;
TSDTS INTERVAL DAY TO SECOND;
TSYTM INTERVAL YEAR TO MONTH;
BEGIN
TS := TO_TIMESTAMP('&ENTER_THE_TIMESTAMP');
TSDTS:= TO_DSINTERVAL('&ENTER_THE_DAY_TO_SECOND');
TSYTM:= TO_YMINTERVAL('&ENTER_THE_YEAR_TO_MONTH');
DBMS_OUTPUT.PUT_LINE('TIMESTAMP: ' || TS);
DBMS_OUTPUT.PUT_LINE('TIMESTAMP + DAY TO SECOND: ' || (TS + TSDTS));
DBMS_OUTPUT.PUT_LINE('TIMESTAMP + YEAR TO MONTH: ' || (TS - TSYTM));
END;
/