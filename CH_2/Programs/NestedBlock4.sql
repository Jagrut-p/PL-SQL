IN BLOCK THREE : DISPLAY PRODUCT OF ANY TWO 'A' VARIABLES

IN BLOCK TWO : DISPLAY SUBTRACTION OF ANY TWO

IN BLOCK ONE : DISPLAY ADDITION OF 'A' VARIABLES OF BLOCKS ONE AND TWO
