VAR PTWO NUMBER
<<ONE>>
DECLARE
A NUMBER := 10;
       BEGIN
<<TWO>>
           DECLARE
		       A NUMBER := 20;
			   BEGIN
			   --TWO
		   <<THREE>>
		       DECLARE
			   A NUMBER := 30;
               BEGIN
			   --THREE
               DBMS_OUTPUT.PUT_LINE(ONE.A + TWO.A);
               DBMS_OUTPUT.PUT_LINE(TWO.A * THREE.A);
		       END;
        DBMS_OUTPUT.PUT_LINE(TWO.A - ONE.A);
		:PTWO := A;
      END;
DBMS_OUTPUT.PUT_LINE(:PTWO + ONE.A);
END;
/
