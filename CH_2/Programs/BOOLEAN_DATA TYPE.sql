/*
DECLARE SINGLE BOOLEAN VARIABLE.

ASK FOR IT'S VALUE.

RUN IT 3 TIMES.

EACH TIME SUPPLY 3 DIFFERENT VALUE I.E. TRUE , FALSE , NULL

DON'T USE PLSQL STATEMENTS 'IF' OR 'CASE', BUT YOU CAN USE ALL SQL FUNCTIONS.

DISPLAY 'TRUE' IF ENTERED VALUE IS TRUE

DISPLAY 'FALSE' IF ENTERED VALUE IS FALSE

DISPLAY 'NULL' IF ENTERED VALUE IS NULL
*/
DECLARE 
VAL BOOLEAN;
BEGIN
VAL:= &ENTER_THE_VALUE;
DBMS_OUTPUT.PUT_LINE('VAL: ' || CASE WHEN VAL THEN 'TRUE' WHEN VAL = FALSE THEN 'FALSE' ELSE 'NULL' END);
DBMS_OUTPUT.PUT_LINE('VAL: ' || CASE WHEN NOT VAL IS NULL THEN 'FALSE' ELSE 'TRUE' END);
END;
