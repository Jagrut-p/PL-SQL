/*
DECLARE 4 VARIABLES. : P Q R S

USE ALL DATA TYPES : BINARY_INTEGER , PLS_INTEGER , BINARY_FLOAT AND BINARY_DOUBLE.

ASSIGN SOME VALUES TO ALL OF THEM.

DISPLAY THEM ALL IN ORIGINAL AND DECIMAL FORMAT.

ADD P AND Q

SUBTRACT P FROM Q

MULTIPLY Q AND R

DIVIDE R BY S

DISPLAY ALL OF THEM IN ORIGINAL AND DECIMAL FORMAT.
*/
DECLARE 
P BINARY_INTEGER := 123;
Q PLS_INTEGER := 456;
R BINARY_FLOAT := 355;
S BINARY_DOUBLE := 59;
BEGIN
DBMS_OUTPUT.PUT_LINE('P: ' || P);
DBMS_OUTPUT.PUT_LINE('Q: ' || Q);
DBMS_OUTPUT.PUT_LINE('R: ' || R);
DBMS_OUTPUT.PUT_LINE('S: ' || S);
DBMS_OUTPUT.PUT_LINE('-------------------------------------');
DBMS_OUTPUT.PUT_LINE('P+Q: ' || TO_CHAR(P,'999.99'));
DBMS_OUTPUT.PUT_LINE('P-Q: ' || TO_CHAR(Q,'000.99'));
DBMS_OUTPUT.PUT_LINE('Q*R: ' || TO_CHAR(R,'999.00'));
DBMS_OUTPUT.PUT_LINE('R/S: ' || TO_CHAR(S,'990.99'));
DBMS_OUTPUT.PUT_LINE('-------------------------------------');
DBMS_OUTPUT.PUT_LINE('P+Q: ' || (P+Q));
DBMS_OUTPUT.PUT_LINE('P-Q: ' || (P-Q));
DBMS_OUTPUT.PUT_LINE('Q*R: ' || (Q*R));
DBMS_OUTPUT.PUT_LINE('R/S: ' || (R/S));
DBMS_OUTPUT.PUT_LINE('-------------------------------------');
DBMS_OUTPUT.PUT_LINE('P+Q: ' || TO_CHAR(P+Q,'9999.00'));
DBMS_OUTPUT.PUT_LINE('P-Q: ' || TO_CHAR(P-Q,'0000.99'));
DBMS_OUTPUT.PUT_LINE('Q*R: ' || TO_CHAR(Q*R,'9999.00'));
DBMS_OUTPUT.PUT_LINE('R/S: ' || TO_CHAR(R/S,'0000.99'));
END;
/